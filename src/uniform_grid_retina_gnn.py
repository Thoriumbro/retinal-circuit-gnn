def radius_edges(src_pos, dst_pos, radius, max_k=None):
    """Directed edges src->dst for every dst within `radius`, with a Gaussian
    distance-decay weight (synaptic strength falls off with distance), normalized
    so each destination's incoming weights sum to 1 (stable pooling)."""
    tree = cKDTree(src_pos)
    rows, cols, dist = [], [], []
    for j, p in enumerate(dst_pos):
        idx = tree.query_ball_point(p, radius)
        if not idx:                                   # guarantee >=1 input
            idx = [int(tree.query(p, 1)[1])]
        if max_k and len(idx) > max_k:                # keep the nearest max_k
            d = np.linalg.norm(src_pos[idx] - p, axis=1)
            idx = list(np.array(idx)[np.argsort(d)[:max_k]])
        for i in idx:
            rows.append(i); cols.append(j)
            dist.append(float(np.linalg.norm(src_pos[i] - p)))
    cols = np.asarray(cols); d = np.asarray(dist)
    sigma = radius / 2 + 1e-9
    w = np.exp(-(d ** 2) / (2 * sigma ** 2))          # strength decays with distance
    denom = np.zeros(len(dst_pos)); np.add.at(denom, cols, w)
    w = w / (denom[cols] + 1e-9)                       # normalize per destination
    ei = torch.tensor(np.array([rows, cols]), dtype=torch.long)  # [src; dst]
    return ei, torch.tensor(w, dtype=torch.float)

