from torch_geometric.nn import GraphConv
INTERNEURONS = ['horizontal', 'bipolar', 'amacrine', 'ganglion']
STIM_NODES   = ['photoreceptor', 'horizontal', 'bipolar', 'amacrine']  # carry a pooled-stimulus time-series
RELATIONS    = list(edge_index_dict.keys())
RF_FEAT      = 64                                                       # RF-CNN output width

class RetinaGNN(nn.Module):
    def __init__(self, hidden=HIDDEN, rounds=N_ROUNDS, dropout=0.1):
        super().__init__()
        # Shared temporal front-end applied to EVERY stimulus-carrying node
        # type. No pooling over time -> the 40-frame timeline survives.
        # BatchNorm mirrors the Stanford CNN's design.
        self.temporal = nn.Sequential(
            nn.Conv1d(1, 16, 7, padding=3),  nn.BatchNorm1d(16), nn.ReLU(),
            nn.Conv1d(16, 16, 5, padding=2), nn.BatchNorm1d(16), nn.ReLU(),
        )
        self.node_proj = nn.ModuleDict({t: nn.Linear(16 * WINDOW, hidden) for t in STIM_NODES})

        # Learned identity per interneuron (added to the stimulus features so
        # each node keeps a stable "who am I", but is no longer purely static).
        self.emb = nn.ModuleDict({t: nn.Embedding(NODE_COUNTS[t], hidden) for t in INTERNEURONS})

        self.convs = nn.ModuleList([HeteroConv({rel: GraphConv((-1, -1), hidden) for rel in RELATIONS},
                                                aggr='sum') for _ in range(rounds)])
        self.norms = nn.ModuleList([nn.ModuleDict({t: nn.LayerNorm(hidden)
                     for t in ['photoreceptor'] + INTERNEURONS}) for _ in range(rounds)])
        self.drop = nn.Dropout(dropout)

        # RF-CNN branch: spatiotemporal conv over each ganglion cell's
        # (WINDOW x 11 x 11) patch. Space is collapsed, the full 40-frame
        # timeline is KEPT (was AdaptiveAvgPool3d(1) = averaged time away).
        self.rfcnn = nn.Sequential(
            nn.Conv3d(1, 16, (7, 3, 3), padding=(3, 1, 1)),  nn.BatchNorm3d(16), nn.ReLU(),
            nn.MaxPool3d((1, 2, 2)),
            nn.Conv3d(16, 32, (5, 3, 3), padding=(2, 1, 1)), nn.BatchNorm3d(32), nn.ReLU(),
            nn.MaxPool3d((1, 2, 2)),
            nn.Conv3d(32, 32, (5, 3, 3), padding=(2, 1, 1)), nn.BatchNorm3d(32), nn.ReLU(),
            nn.AdaptiveAvgPool3d((WINDOW, 1, 1)),
        )
        self.rf_head = nn.Sequential(nn.Flatten(),
                                     nn.Linear(32 * WINDOW, RF_FEAT), nn.ReLU())

        self.readout = nn.Sequential(
            nn.Linear(hidden * rounds + RF_FEAT, hidden), nn.ReLU(), nn.Dropout(dropout))
        self.cell_w = nn.Embedding(N_GANG, hidden)   # per-cell readout weights
        self.cell_b = nn.Embedding(N_GANG, 1)
        nn.init.normal_(self.cell_w.weight, std=0.05)
        nn.init.constant_(self.cell_b.weight, -1.0)

    def _encode(self, x_pooled):                 # (N, WINDOW) -> (N, 16*WINDOW)
        return self.temporal(x_pooled.unsqueeze(1)).flatten(1)

    def forward(self, data):
        x = {}
        for t in STIM_NODES:
            feat = self.node_proj[t](self._encode(data[t].x))
            if t != 'photoreceptor':
                feat = feat + self.emb[t](data[t].nid)
            x[t] = feat
        x['ganglion'] = self.emb['ganglion'](data['ganglion'].nid)

        ei = data.edge_index_dict
        ew = {rel: data[rel].edge_weight for rel in RELATIONS}
        gang_states = []
        for conv, norm in zip(self.convs, self.norms):
            out = conv(x, ei, edge_weight_dict=ew)
            x = {k: self.drop(norm[k](F.relu(out[k] + x[k]))) for k in out}
            gang_states.append(x['ganglion'])
        g = torch.cat(gang_states, dim=-1)

        rf = data['ganglion'].rf.view(-1, 1, WINDOW, PATCH, PATCH)
        rf = self.rf_head(self.rfcnn(rf))
        h  = self.readout(torch.cat([g, rf], dim=-1))
        nid = data['ganglion'].nid
        out = (h * self.cell_w(nid)).sum(-1) + self.cell_b(nid).squeeze(-1)
        return F.softplus(out)

