def knn_edges(src_pos, dst_pos, k):
    """k-NN convergence for the ganglion-facing layers — the radius cutoff
    above was giving each ganglion node only 1-2 upstream cells (6 total
    b2g edges, 4 total a2g edges for 4 ganglion nodes). k is chosen from
    typical RGC dendritic-convergence ratios, not tuned against val corr."""
    tree = cKDTree(src_pos)
    rows, cols, dist = [], [], []
    for j, p in enumerate(dst_pos):
        k_eff = min(k, len(src_pos))
        d, idx = tree.query(p, k=k_eff)
        idx = np.atleast_1d(idx); d = np.atleast_1d(d)
        for i, di in zip(idx, d):
            rows.append(int(i)); cols.append(j); dist.append(float(di))
    cols = np.asarray(cols); d = np.asarray(dist)
    sigma = d.mean() / 2 + 1e-9
    w = np.exp(-(d ** 2) / (2 * sigma ** 2))
    denom = np.zeros(len(dst_pos)); np.add.at(denom, cols, w)
    w = w / (denom[cols] + 1e-9)
    ei = torch.tensor(np.array([rows, cols]), dtype=torch.long)
    return ei, torch.tensor(w, dtype=torch.float)

