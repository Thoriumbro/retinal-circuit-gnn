def make_mosaic(n, jitter=0.35, seed=0):
    r = np.random.default_rng(seed)
    side = int(np.ceil(np.sqrt(n)))
    xs, ys = np.meshgrid(np.linspace(0, 1, side), np.linspace(0, 1, side))
    pts = np.stack([xs.ravel(), ys.ravel()], 1)[:n]
    pts = pts + r.uniform(-jitter / side, jitter / side, pts.shape)
    return np.clip(pts, 0, 1).astype(np.float32)

def _shape(n):
    """Most-square (rows, cols) factorisation of n."""
    best = (1, n)
    for r in range(1, int(np.sqrt(n)) + 1):
        if n % r == 0:
            best = (r, n // r)
    return best

def make_grid(n):
    """Complete rectangular lattice at cell centres of [0,1]^2. No truncation."""
    rows, cols = _shape(n)
    xs = (np.arange(cols) + 0.5) / cols
    ys = (np.arange(rows) + 0.5) / rows
    X, Y = np.meshgrid(xs, ys)
    return np.stack([X.ravel(), Y.ravel()], 1).astype(np.float32)

def spacing(n):
    """Geometric-mean nearest-neighbour spacing of the lattice for n nodes."""
    rows, cols = _shape(n)
    return float(np.sqrt((1.0 / rows) * (1.0 / cols)))

